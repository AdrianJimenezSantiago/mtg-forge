class Translations:
    """Wrapper que permite acceder a las traducciones como atributos (``t.nav_decks``)
    o como dict (``t['nav_decks']``). Devuelve la clave entre corchetes como
    fallback si no existe, para que sea fácil detectar cadenas sin traducir."""

    def __init__(self, lang: str) -> None:
        self._lang = lang
        self._data: dict[str, str] = _TRANSLATIONS.get(lang, _TRANSLATIONS["es"])

    def __getattr__(self, key: str) -> str:
        return self._data.get(key, f"[{key}]")

    def __getitem__(self, key: str) -> str:
        return self._data.get(key, f"[{key}]")

    def get(self, key: str, default: str = "") -> str:
        return self._data.get(key, default)

    def as_dict(self) -> dict[str, str]:
        """Devuelve el dict completo (para inyectar en window._T desde JS)."""
        return dict(self._data)


def get_translations(lang: str) -> Translations:
    """Devuelve el objeto de traducciones para el idioma indicado.
    Si el idioma no existe, cae al español."""
    supported = set(_TRANSLATIONS.keys())
    return Translations(lang if lang in supported else "es")


def detect_lang(request_or_cookie: Any) -> str:
    """Detecta el idioma preferido desde la cookie ``lang``.
    Compatible con FastAPI Request o un dict de cookies."""
    if hasattr(request_or_cookie, "cookies"):
        cookie = request_or_cookie.cookies.get("lang", "es")
    elif isinstance(request_or_cookie, dict):
        cookie = request_or_cookie.get("lang", "es")
    else:
        cookie = "es"
    return cookie if cookie in _TRANSLATIONS else "es"
